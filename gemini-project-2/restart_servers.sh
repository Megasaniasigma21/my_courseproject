#!/usr/bin/env bash
# ==============================================================================
# Скрипт перезапуска всех серверов Bochflix (Nginx + FastAPI)
# ==============================================================================

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_DIR" || exit 1

echo "=========================================="
echo "🔄 Перезапуск серверов Bochflix..."
echo "=========================================="

# 1. Полная остановка текущих сервисов
./stop_servers.sh

echo ""
echo "[*] Ожидание 1 сек перед повторным запуском..."
sleep 1

# 2. Запуск серверов
exec ./start_servers.sh "$@"
